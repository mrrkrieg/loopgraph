import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const packsRoot = path.join(repoRoot, "packs", "official");
const outputPath = path.join(repoRoot, "packages", "loopgraph", "src", "generated", "official-app-catalog.ts");
const mode = process.argv.includes("--check") ? "check" : "write";

const departmentKey = {
  product: "product",
  marketing: "marketing",
  sales: "sales",
  customer_success: "customer_success",
  engineering: "engineering",
  ops_finance: "operations_finance",
  hr_talent: "hr",
  legal_compliance: "legal_security",
  management: "management"
};

const packRoots = await discoverPackRoots();
const entries = [];
for (const packRoot of packRoots) entries.push(...await compilePack(packRoot));

const payload = {
  schemaVersion: "loopgraph-generated-app-catalog/v1alpha1",
  sourceDigest: digest(entries),
  entries
};
const output = `/* This file is generated by scripts/generate-official-app-catalog.mjs. Do not edit it directly. */\n\nexport const GENERATED_OFFICIAL_APP_CATALOG = ${JSON.stringify(payload, null, 2)} as const;\n`;

if (mode === "check") {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== output) {
    console.error("Generated official app catalog is stale. Run: npm run generate:app-catalog");
    process.exitCode = 1;
  } else {
    console.log(`Official app catalog is current (${entries.length} loops, ${payload.sourceDigest}).`);
  }
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, output, "utf8");
  console.log(`Generated ${path.relative(repoRoot, outputPath)} (${entries.length} loops, ${payload.sourceDigest}).`);
}

async function discoverPackRoots() {
  const departments = await readdir(packsRoot, { withFileTypes: true });
  const roots = [];
  for (const department of departments.filter((entry) => entry.isDirectory()).sort(byName)) {
    const departmentRoot = path.join(packsRoot, department.name);
    const apps = await readdir(departmentRoot, { withFileTypes: true });
    for (const app of apps.filter((entry) => entry.isDirectory()).sort(byName)) {
      const appRoot = path.join(departmentRoot, app.name);
      if (await readFile(path.join(appRoot, "loopgraph.pack.yaml"), "utf8").catch(() => undefined)) roots.push(appRoot);
    }
  }
  return roots;
}

async function compilePack(packRoot) {
  const manifest = await readYaml(path.join(packRoot, "loopgraph.pack.yaml"));
  const connectors = await Promise.all((manifest.entrypoints.connectors ?? []).map((relativePath) =>
    readYaml(path.join(packRoot, relativePath))
  ));
  for (const connector of connectors) validateOfficialConnectorMappingOwnership(connector, packRoot);
  const loops = await Promise.all(manifest.entrypoints.loops.map((relativePath) => readYaml(path.join(packRoot, relativePath))));
  const dashboards = await Promise.all((manifest.entrypoints.dashboards ?? []).map((relativePath) => readYaml(path.join(packRoot, relativePath))));
  const appMetrics = uniqueBy(dashboards.flatMap((dashboard) => dashboard.metrics ?? []), (metric) => metric.id);
  const loopsById = new Map(loops.map((loop) => [loop.metadata.id, loop]));
  return loops.map((loop) => compileLoop({ manifest, loop, loopsById, appMetrics, packRoot }));
}

function validateOfficialConnectorMappingOwnership(connector, packRoot) {
  const missing = (connector.fieldMappings ?? [])
    .filter((mapping) => typeof mapping.providerId !== "string" || mapping.providerId.length === 0)
    .map((mapping) => mapping.objectType ?? "unknown");
  if (missing.length > 0) {
    throw new Error(`Official connector ${connector.id} in ${path.relative(repoRoot, packRoot)} must declare providerId for field mappings: ${missing.join(", ")}`);
  }
}

function compileLoop({ manifest, loop, loopsById, appMetrics, packRoot }) {
  const routing = loop.routing;
  const department = manifest.metadata.department;
  const uiDepartment = departmentKey[department];
  if (!uiDepartment) throw new Error(`Unsupported official pack department: ${department}`);
  const accepts = routing.accepts ?? [];
  const topologyFlows = manifest.topology?.flows ?? [];
  const supportingLoopTemplateIds = topologyFlows
    .filter((flow) => flow.type === "supports" && flow.source?.kind === "loop" && flow.source.id === loop.metadata.id)
    .map((flow) => flow.target.id)
    .sort();
  const learningTargetDepartments = topologyFlows
    .filter((flow) => flow.type === "learning_return" && flow.source?.kind === "loop" && flow.source.id === loop.metadata.id && flow.target?.kind === "loop")
    .map((flow) => loopsById.get(flow.target.id)?.metadata?.department)
    .filter(Boolean);
  const outcomeMetrics = uniqueBy([...(loop.outcomes ?? []), ...appMetrics], (metric) => metric.metric ?? metric.id);
  const primaryOutcome = loop.outcomes?.[0] ?? appMetrics[0];
  const requiredConnections = unique(routing.requiredConnections ?? loop.capabilities.filter((capability) => capability.required).map((capability) => capability.key));
  const allConnections = unique([...requiredConnections, ...loop.capabilities.map((capability) => capability.key), ...(manifest.requiredCapabilities ?? [])]);
  const requiredContext = unique(accepts.flatMap((rule) => rule.requiredFields ?? []).concat(loop.input.requiredFields ?? []));
  const subjectTypes = unique(accepts.flatMap((rule) => rule.subjectTypes ?? []).concat(loop.input.subjectTypes ?? []));
  const packRelativeRoot = toPosix(path.relative(repoRoot, packRoot));
  const verification = unique([
    `Required context must resolve: ${requiredContext.join(", ")}.`,
    `Evidence must remain traceable to the affected ${subjectTypes.join(", ")}.`,
    ...loop.routine.filter((step) => step.type === "verify").map((step) => step.description),
    ...loop.policy.forbiddenActions.map((action) => action.reason),
    `Hermes must ${routing.ambiguityPolicy === "request_human" ? "request human judgment" : routing.ambiguityPolicy} when the route is ambiguous.`
  ]).slice(0, 6);
  const escalation = unique([
    `Escalate to ${humanize(loop.policy.escalationOwner)} within ${loop.policy.escalationSla}.`,
    loop.policy.separateCustomerFacingApproval
      ? "Customer-facing actions require a separate exact approval."
      : "Apply the pack policy before any external action.",
    ...loop.policy.forbiddenActions.map((action) => action.reason),
    `Use ${routing.noMatchPolicy} when no routing contract matches.`
  ]).slice(0, 6);
  const metrics = unique(outcomeMetrics.map((metric) => humanize(metric.metric ?? metric.id)));
  while (metrics.length < 3) metrics.push(["Routing correction rate", "Human review minutes", "Verified outcome rate"][metrics.length]);

  return {
    app: {
      id: manifest.metadata.id,
      name: manifest.metadata.name,
      version: manifest.metadata.version,
      department,
      summary: manifest.metadata.summary,
      sourcePath: packRelativeRoot
    },
    definition: {
      schemaVersion: "company-loop-library/v1alpha1",
      templateId: loop.metadata.id,
      departmentType: department,
      problemTypes: unique(routing.problemTypes),
      eventTypes: unique(accepts.map((rule) => rule.eventTypePattern)),
      subjectTypes,
      requiredContext,
      requiredConnections,
      exclusionRules: (routing.excludes ?? []).map((rule) => ({
        eventTypePattern: rule.eventTypePattern,
        fields: rule.fields ?? [],
        reason: rule.reason
      })),
      fanoutPolicy: routing.fanoutPolicy,
      priority: routing.priority,
      minimumConfidence: routing.minimumConfidence,
      supportingLoopTemplateIds,
      learningOutputs: unique((loop.outcomes ?? []).map((outcome) => `${humanize(outcome.metric)}: ${outcome.description}`)),
      learningConsumers: unique([department, ...learningTargetDepartments, "management"]),
      shouldRouteExamples: unique(routing.examples?.shouldRoute ?? accepts.map((rule) => rule.reason)),
      shouldNotRouteExamples: unique(routing.examples?.shouldNotRoute ?? (routing.excludes ?? []).map((rule) => rule.reason))
    },
    template: {
      id: loop.metadata.id,
      department: uiDepartment,
      loopType: loop.metadata.tags?.[0] ?? loop.metadata.id,
      name: loop.metadata.name,
      description: loop.metadata.description,
      runtimeLevel: "runnable",
      goal: loop.metadata.description,
      businessOutcome: primaryOutcome?.description ?? manifest.metadata.summary,
      primaryMetric: metrics[0],
      secondaryMetrics: metrics.slice(1, 5),
      observes: unique([...subjectTypes.map(humanize), ...requiredContext.map(humanize)]),
      requiredDataSources: allConnections.slice(0, Math.max(3, allConnections.length)).map(humanize),
      routine: loop.routine.map((step) => step.description),
      verification,
      escalation,
      examplePath: packRelativeRoot,
      fixturePaths: (loop.input.fixtures ?? []).map((fixture) => `${packRelativeRoot}/${fixture.path}`)
    }
  };
}

async function readYaml(filePath) {
  return YAML.parse(await readFile(filePath, "utf8"));
}

function unique(values) {
  return [...new Set(values.filter((value) => typeof value === "string" && value.length > 0))];
}

function uniqueBy(values, key) {
  const seen = new Set();
  return values.filter((value) => {
    const id = key(value);
    if (!id || seen.has(id)) return false;
    seen.add(id);
    return true;
  });
}

function humanize(value) {
  return String(value).replaceAll("_", " ").replaceAll(".", " ").replace(/\b\w/g, (letter) => letter.toUpperCase());
}

function digest(value) {
  return `sha256:${createHash("sha256").update(JSON.stringify(value)).digest("hex")}`;
}

function toPosix(value) {
  return value.split(path.sep).join("/");
}

function byName(left, right) {
  return left.name.localeCompare(right.name);
}
